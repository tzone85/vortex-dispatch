package improve

import (
	"context"
	"fmt"
	"strings"
)

// ApplyDeterministicFixes runs the tool-produced fix for each deterministic
// finding directly in root. It never executes FixCommand strings: argv is built
// from the typed fields. It returns a description of each fix applied.
func ApplyDeterministicFixes(ctx context.Context, runner CommandRunner, root string, findings []SelfFinding) ([]string, error) {
	var applied []string

	var gofmtTargets []string
	seen := map[string]bool{}
	tidy := false
	for _, f := range findings {
		if !f.Deterministic {
			continue
		}
		switch f.Check {
		case CheckGofmt:
			if !validRepoRelativeGoFile(root, f.Target) {
				return applied, fmt.Errorf("refusing to gofmt unsafe path %q", f.Target)
			}
			if !seen[f.Target] {
				seen[f.Target] = true
				gofmtTargets = append(gofmtTargets, f.Target)
			}
		case CheckModTidy:
			tidy = true
		}
	}

	if len(gofmtTargets) > 0 {
		args := append([]string{"-w"}, gofmtTargets...)
		out, code, err := runner.Run(ctx, root, "gofmt", args...)
		if err != nil || code != 0 {
			return applied, fmt.Errorf("gofmt -w failed (exit %d): %s", code, toolFailure(err, out))
		}
		applied = append(applied, fmt.Sprintf("gofmt -w (%d file(s))", len(gofmtTargets)))
	}
	if tidy {
		out, code, err := runner.Run(ctx, root, "go", "mod", "tidy")
		if err != nil || code != 0 {
			return applied, fmt.Errorf("go mod tidy failed (exit %d): %s", code, toolFailure(err, out))
		}
		applied = append(applied, "go mod tidy")
	}
	return applied, nil
}

// gofmtTargetsOf returns the deterministic gofmt targets of a report.
func gofmtTargetsOf(findings []SelfFinding) []string {
	var out []string
	for _, f := range findings {
		if f.Deterministic && f.Check == CheckGofmt {
			out = append(out, f.Target)
		}
	}
	return out
}

// SelfHeal applies every deterministic finding on a fresh branch off main and
// opens one PR for it. It returns attempted=false when there was nothing
// deterministic to fix.
func (impl *Implementer) SelfHeal(ctx context.Context, rep SelfAuditReport, date string) (ImplementResult, bool) {
	var res ImplementResult
	det := rep.DeterministicFindings()
	if len(det) == 0 {
		return res, false
	}

	branch := fmt.Sprintf("vxd-improve/%s-self-heal", date)
	res.Branch = branch

	if impl.dryRun {
		res.Disposition = "proposed"
		return res, true
	}

	fail := func(msg string) (ImplementResult, bool) {
		res.Disposition = "aborted"
		res.Error = msg
		return res, true
	}

	// Only the paths self-heal will stage matter: the daily run legitimately
	// dirties docs/self-improvement/ before this point, and unrelated changes
	// can never leak into the commit because staging is by explicit path.
	stagePaths := append([]string{"go.mod", "go.sum"}, gofmtTargetsOf(det)...)
	statusArgs := append([]string{"status", "--porcelain", "--"}, stagePaths...)
	status, err := impl.gitOutput(statusArgs...)
	if err != nil {
		return fail(fmt.Sprintf("git status: %v", err))
	}
	if status != "" {
		return fail("files self-heal would touch are already modified; refusing to self-heal:\n" + status)
	}

	if err := impl.git("checkout", "-b", branch, "main"); err != nil {
		impl.git("checkout", "main")
		return fail(fmt.Sprintf("create branch: %v", err))
	}

	applied, err := ApplyDeterministicFixes(ctx, ExecRunner{}, impl.repoPath, det)
	if err != nil {
		impl.abandon(branch)
		return fail(fmt.Sprintf("apply fixes: %v", err))
	}

	// Stage by explicit path only. go.sum may legitimately be absent, so add
	// paths one at a time and ignore the individual error.
	for _, p := range stagePaths {
		_ = impl.git("add", "--", p)
	}
	if err := impl.git("diff", "--cached", "--quiet"); err == nil {
		impl.abandon(branch)
		return fail("fixes produced no diff")
	}

	msg := fmt.Sprintf("chore(self-heal): gofmt + go mod tidy\n\nApplied by VXD self-audit %s.", date)
	if err := impl.git("commit", "-m", msg); err != nil {
		impl.abandon(branch)
		return fail(fmt.Sprintf("commit: %v", err))
	}

	for _, g := range impl.qualityGates() {
		if err := g.fn(); err != nil {
			impl.abandon(branch)
			return fail(fmt.Sprintf("gate %s: %v", g.name, err))
		}
	}
	res.TestsPassed = true
	stat, _ := impl.gitOutput("diff", "--shortstat", "main...HEAD")
	res.FilesChanged, res.LinesChanged = parseDiffStat(stat)

	if err := impl.push(branch); err != nil {
		return fail(fmt.Sprintf("push: %v", err))
	}

	body := "## Self-Heal\n\nDeterministic fixes found by the VXD self-audit:\n\n"
	for _, a := range applied {
		body += "- " + a + "\n"
	}
	body += "\n---\n*Generated by VXD Self-Improvement Engine*"
	prURL, err := impl.openPR(fmt.Sprintf("chore(self-heal): gofmt + go mod tidy (%s)", date), body, branch)
	if err != nil {
		return fail(fmt.Sprintf("create PR: %v", err))
	}

	res.PRURL = prURL
	res.Disposition = "implemented"
	impl.git("checkout", "main")
	return res, true
}

func toolFailure(err error, out string) string {
	out = strings.TrimSpace(out)
	if err != nil && out == "" {
		return err.Error()
	}
	if err != nil {
		return err.Error() + ": " + out
	}
	return out
}
